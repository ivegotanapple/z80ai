/*
 * Z80-uLM inference (https://github.com/HarryR/z80ai) ported to the Game Boy.
 *
 * Same semantics as buildz80com.py:
 *   input    : 128 trigram buckets of the query + 128 buckets of context
 *              (the last 8 characters produced), +32 per occurrence
 *   layers   : acc = sum(weight * input) + bias (16 bits, wrapping),
 *              then an arithmetic shift right by 2; ReLU on hidden layers
 *   output   : argmax (first maximum), EOS = last character of the character set
 *
 * Implementation difference: the computation is done "per input" and skips zero
 * inputs (the query and the ReLU outputs contain many). The result is bit-for-bit
 * identical because addition modulo 2^16 is commutative and 0 * w = 0.
 *
 * Input text: the model was trained on ASCII only, so accented letters typed on
 * the keyboard are folded to their base letter (e.g. an e with an acute accent
 * becomes e). This only affects non-ASCII input; ASCII input matches the Z80 binary.
 */

#include <gb/gb.h>
#include <stdint.h>
#include <string.h>
#include "lm.h"
#include "lm_model.h"

#define MAX_N 256

static lm_layer_t layers[LM_NLAYERS];

static uint8_t  in_cnt[256];        /* 0..127 query, 128..255 context (occurrence counts) */
static char     ctx[8];             /* last 8 characters produced, lowercase */
static uint8_t  gen_left;

static uint8_t  list_idx[MAX_N];    /* non-zero inputs of the current layer */
static uint16_t list_val[MAX_N];
static uint8_t  list_n;

static uint16_t buf_a[MAX_N];
static uint16_t buf_b[MAX_N];

static uint8_t inited;

/* ---------- Input: trigram hashing ---------- */

static uint8_t lower(uint8_t c) {
    return (c >= 'A' && c <= 'Z') ? (uint8_t)(c + 32) : c;
}

/* Base letters for the Windows-1252 / Latin-1 range 0xC0..0xFF */
static const char fold_tab[] =
    "aaaaaaaceeeeiiii"      /* C0..CF */
    "dnoooooxouuuuyts"      /* D0..DF */
    "aaaaaaaceeeeiiii"      /* E0..EF */
    "dnooooo/ouuuuyty";     /* F0..FF */

/* Lowercase and fold accents; this is what the tokenizer hashes. */
static uint8_t norm(uint8_t c) {
    if (c >= 'A' && c <= 'Z') return (uint8_t)(c + 32);
    if (c >= 0xC0) return (uint8_t)fold_tab[c - 0xC0];
    if (c == 0x8C || c == 0x9C) return 'o';      /* OE, oe */
    if (c == 0x80) return 'e';                   /* euro */
    return c;
}

/* Only the low 7 bits matter, so 8-bit arithmetic is enough. */
static void tok_hash(uint8_t c1, uint8_t c2, uint8_t c3) {
    uint8_t h = (uint8_t)(c1 * 31 + c2);
    h = (uint8_t)(h * 31 + c3);
    in_cnt[h & 127]++;
}

static void encode_ctx(void) {
    uint8_t n, pos, k, h;
    memset(&in_cnt[128], 0, 128);
    for (n = 1; n <= 3; n++) {
        for (pos = 0; pos < 9 - n; pos++) {
            h = (uint8_t)(pos * 7);
            for (k = 0; k < n; k++) h = (uint8_t)(h * 31 + (uint8_t)ctx[pos + k]);
            in_cnt[128 + (h & 127)]++;
        }
    }
}

void lm_start(const char *text) {
    uint8_t c1, c2, c3;

    if (!inited) {
        lm_load_table(layers);
        inited = 1;
    }
    memset(in_cnt, 0, sizeof in_cnt);
    memset(ctx, ' ', sizeof ctx);
    gen_left = LM_MAX_OUT;

    while (*text == ' ') text++;
    if (!*text) return;

    c1 = ' ';
    c2 = norm((uint8_t)*text++);
    while (*text) {
        c3 = norm((uint8_t)*text++);
        tok_hash(c1, c2, c3);
        c1 = c2;
        c2 = c3;
    }
    tok_hash(c1, c2, ' ');
}

/* ---------- Layer ---------- */

/* Assembly kernel (lm_kernel.s, generated by tools/gen_kernel.py):
 * acc[0..8*np-1] += x * weight, weights read from ROM starting at ax_p. */
extern uint16_t        *ax_o;
extern const uint8_t   *ax_p;
extern uint16_t         ax_x;
extern uint8_t          ax_np;
void lm_axpy(void);

/* Computes out = (bias + sum over the input list) >> 2, then ReLU if hidden.
 * If hidden, also builds the list of non-zero outputs for the next layer. */
static void run_layer(const lm_layer_t *L, uint16_t *out, uint8_t hidden) {
    uint8_t e, nb = L->rowbytes;
    uint16_t n, nout = L->nout;
    int16_t v;

    SWITCH_ROM(L->bank);
    for (n = 0; n < nout; n++) out[n] = (uint16_t)L->b[n];

    for (e = 0; e < list_n; e++) {
        ax_x = list_val[e];
        ax_o = out;
        ax_p = L->w + (uint16_t)list_idx[e] * nb;
        ax_np = (uint8_t)(nb >> 1);
        lm_axpy();
    }

    list_n = 0;
    for (n = 0; n < nout; n++) {
        v = ((int16_t)out[n]) >> 2;
        if (hidden) {
            if (v < 0) v = 0;
            if (v) {
                list_idx[list_n] = (uint8_t)n;
                list_val[list_n] = (uint16_t)v;
                list_n++;
            }
        }
        out[n] = (uint16_t)v;
    }
}

/* ---------- Generation ---------- */

char lm_step(void) {
    uint8_t j, i, best_i;
    uint16_t *src;
    int16_t best, cur;
    uint8_t ch;
    uint8_t k;

    if (!gen_left) return 0;

    encode_ctx();

    /* inputs of the first layer: value = occurrences * 32 */
    list_n = 0;
    for (j = 0; j < 255; j++) {
        if (in_cnt[j]) {
            list_idx[list_n] = j;
            list_val[list_n] = (uint16_t)in_cnt[j] << 5;
            list_n++;
        }
    }
    if (in_cnt[255]) {          /* j == 255, handled apart so the 8-bit loop counter does not overflow */
        list_idx[list_n] = 255;
        list_val[list_n] = (uint16_t)in_cnt[255] << 5;
        list_n++;
    }

    src = buf_a;
    for (i = 0; i < LM_NLAYERS; i++) {
        uint16_t *dst = (i & 1) ? buf_b : buf_a;
        run_layer(&layers[i], dst, (uint8_t)(i < LM_NLAYERS - 1));
        src = dst;
    }

    /* argmax: first maximum, signed 16-bit comparison like the Z80 code (sbc hl,de + sign flag) */
    best = (int16_t)src[0];
    best_i = 0;
    for (i = 1; i < LM_NOUT; i++) {
        cur = (int16_t)src[i];
        if ((int16_t)(uint16_t)((uint16_t)cur - (uint16_t)best) > 0) {
            best = cur;
            best_i = i;
        }
    }

    if (best_i == LM_NCHARS - 1) { gen_left = 0; return 0; }

    ch = (uint8_t)lm_charset[best_i];
    for (k = 0; k < 7; k++) ctx[k] = ctx[k + 1];
    ctx[7] = (char)lower(ch);
    gen_left--;
    return (char)ch;
}
